"""Console + file logging, driven by ``run.log_level`` in the YAML.

Console handler is tqdm-aware: log lines are written through ``tqdm.write`` so a
progress bar is never shredded by a concurrent log record.
"""

from __future__ import annotations

import logging
from pathlib import Path

from tqdm.auto import tqdm

_FORMAT = "%(asctime)s | %(levelname)-7s | %(name)-28s | %(message)s"
_DATEFMT = "%H:%M:%S"


class _TqdmHandler(logging.StreamHandler):
    """Emit through ``tqdm.write`` so progress bars survive log output."""

    def emit(self, record: logging.LogRecord) -> None:
        try:
            tqdm.write(self.format(record))
        except Exception:  # pragma: no cover - logging must never raise
            self.handleError(record)


def setup_logging(level: str = "INFO", log_file: Path | None = None) -> logging.Logger:
    """Configure the ``infinity_skyline`` logger. Idempotent across calls."""
    logger = logging.getLogger("infinity_skyline")
    logger.setLevel(level)
    logger.propagate = False
    for handler in list(logger.handlers):
        logger.removeHandler(handler)
        handler.close()

    console = _TqdmHandler()
    console.setFormatter(logging.Formatter(_FORMAT, datefmt=_DATEFMT))
    logger.addHandler(console)

    if log_file is not None:
        log_file.parent.mkdir(parents=True, exist_ok=True)
        file_handler = logging.FileHandler(log_file, encoding="utf-8")
        file_handler.setFormatter(logging.Formatter(_FORMAT))
        logger.addHandler(file_handler)

    return logger


def get_logger(name: str) -> logging.Logger:
    """Child logger, e.g. ``get_logger(__name__)`` inside a module."""
    return logging.getLogger("infinity_skyline").getChild(name.split(".")[-1])
