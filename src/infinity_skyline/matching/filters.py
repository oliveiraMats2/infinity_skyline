"""Match filters applied between ``knnMatch`` and the geometric verification.

These operate on raw ``cv2.DMatch`` objects so they stay reusable by any matcher
backend, and they never touch the descriptors themselves.
"""

from __future__ import annotations

from typing import Sequence

import cv2

from ..logging_setup import get_logger

logger = get_logger(__name__)


def lowe_ratio_test(
    knn_matches: Sequence[Sequence[cv2.DMatch]],
    ratio: float,
) -> list[cv2.DMatch]:
    """Keep a match when its best neighbour is clearly better than the second one.

    ``knnMatch(k=2)`` can return neighbourhoods with fewer than two entries when the
    train image has almost no keypoints, so those are skipped instead of unpacked.
    """
    kept: list[cv2.DMatch] = []
    for neighbours in knn_matches:
        if len(neighbours) < 2:
            continue
        best, second = neighbours[0], neighbours[1]
        if best.distance < ratio * second.distance:
            kept.append(best)
    return kept


def cross_check_filter(
    ab: Sequence[cv2.DMatch],
    ba: Sequence[cv2.DMatch],
) -> list[cv2.DMatch]:
    """Keep the matches of ``ab`` that ``ba`` confirms in the opposite direction."""
    reverse: dict[int, int] = {m.queryIdx: m.trainIdx for m in ba}
    return [m for m in ab if reverse.get(m.trainIdx, -1) == m.queryIdx]


def max_distance_filter(
    matches: Sequence[cv2.DMatch],
    max_distance: float | None,
) -> list[cv2.DMatch]:
    """Drop matches above a descriptor distance threshold. ``None`` disables it."""
    if max_distance is None:
        return list(matches)
    return [m for m in matches if m.distance <= max_distance]
