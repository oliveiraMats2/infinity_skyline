"""Resume: only a run that wrote its done marker is skipped."""

from pathlib import Path

from typer.testing import CliRunner

from infinity_skyline.cli import DONE_MARKER, app


def test_resume_skips_only_finished_runs(tmp_path: Path) -> None:
    for name in ("finished", "stopped"):
        (tmp_path / f"{name}.yaml").write_text(
            f"run:\n  output_root: {tmp_path / 'results'}\n"
            f"data:\n  input_dir: {tmp_path / 'no_images'}\n"
        )
    (tmp_path / "results" / "finished").mkdir(parents=True)
    (tmp_path / "results" / "finished" / DONE_MARKER).write_text("")
    # A panorama without the marker is a run stopped halfway: it must be redone.
    (tmp_path / "results" / "stopped" / "panorama").mkdir(parents=True)
    (tmp_path / "results" / "stopped" / "panorama" / "panorama.png").write_text("")
    sweep = tmp_path / "sweep.yaml"
    sweep.write_text(
        f"configs:\n  - {tmp_path / 'finished.yaml'}\n  - {tmp_path / 'stopped.yaml'}\nresume: true\n"
    )

    output = CliRunner().invoke(app, ["sweep", "--config", str(sweep)]).output

    assert "finished  skipped" in output
    assert "stopped   FAILED" in output  # it tried again, and there are no images
